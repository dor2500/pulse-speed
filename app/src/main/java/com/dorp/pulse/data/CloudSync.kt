enum class SyncStatus { SYNCING, SYNCED, OFFLINE, ERROR }

enum class AccountError { NO_GOOGLE_PLAY, NO_ACCOUNT, FAILED }

sealed interface AccountState {
    /** This build has no Firebase project (no google-services.json), so sign-in is hidden. */
    data object Unavailable : AccountState
    data object SignedOut : AccountState
    data object SigningIn : AccountState
    data class SignedIn(
        val name: String?,
        val email: String?,
        val photoUrl: String?,
        val sync: SyncStatus,
        val lastSyncedAt: Long? = null,
    ) : AccountState
}

/**
 * Google sign-in through Credential Manager, exchanged for a Firebase session, plus a two-way mirror
 * of the speed test history at `users/{uid}/results/{time}` in Firestore.
 *
 * Sync model: on sign-in, local results the cloud lacks are uploaded (so nothing is lost), then the
 * cloud collection is the source of truth and every change on any device streams in live. Firestore's
 * offline cache queues writes while there's no connection. Signing out keeps the local copy.
 */
class CloudSync(private val app: Application, private val history: HistoryStore, private val scope: CoroutineScope) {
    private val firebase: FirebaseApp? = runCatching {
        FirebaseApp.getApps(app).firstOrNull() ?: FirebaseApp.initializeApp(app)
    }.getOrNull()
    private val auth: FirebaseAuth? = firebase?.let { FirebaseAuth.getInstance(it) }
    private val db: FirebaseFirestore? = firebase?.let { FirebaseFirestore.getInstance(it) }

    /** Generated by the google-services plugin from google-services.json; looked up by name so builds without it still compile. */
    private val webClientId: String? = app.resources
        .getIdentifier("default_web_client_id", "string", app.packageName)
        .takeIf { it != 0 }
        ?.let(app::getString)

    private val _state = MutableStateFlow<AccountState>(
        if (auth == null || db == null || webClientId == null) AccountState.Unavailable else AccountState.SignedOut
    )
    val state: StateFlow<AccountState> = _state.asStateFlow()

    private val _error = MutableStateFlow<AccountError?>(null)
    val error: StateFlow<AccountError?> = _error.asStateFlow()
    fun clearError() { _error.value = null }

    private var listener: ListenerRegistration? = null
    private var syncedUid: String? = null

    init {
        if (_state.value != AccountState.Unavailable) {
            auth!!.addAuthStateListener { onUser(it.currentUser) }
        }
    }

    private fun results(uid: String): CollectionReference =
        db!!.collection("users").document(uid).collection("results")

    private fun onUser(user: FirebaseUser?) {
        if (user == null) {
            stopSync()
            if (_state.value !is AccountState.SigningIn) _state.value = AccountState.SignedOut
            return
        }
        _state.value = AccountState.SignedIn(
            name = user.displayName,
            email = user.email,
            photoUrl = user.photoUrl?.toString(),
            sync = SyncStatus.SYNCING,
            lastSyncedAt = (_state.value as? AccountState.SignedIn)?.lastSyncedAt,
        )
        if (syncedUid != user.uid) startSync(user.uid)
    }

    private fun setSync(status: SyncStatus, synced: Boolean = false) = _state.update {
        if (it is AccountState.SignedIn) it.copy(sync = status, lastSyncedAt = if (synced) System.currentTimeMillis() else it.lastSyncedAt) else it
    }

    private fun startSync(uid: String) {
        stopSync()
        syncedUid = uid
        var first = true
        listener = results(uid)
            .orderBy("t", Query.Direction.DESCENDING)
            .limit(MAX_SYNCED.toLong())
            .addSnapshotListener { snap, err ->
                if (err != null || snap == null) {
                    Log.w(TAG, "history listener failed", err)
                    setSync(SyncStatus.ERROR)
                    return@addSnapshotListener
                }
                val remote = snap.documents.mapNotNull(::fromDoc)
                if (first) {
                    first = false
                    // Merge: anything only this device has goes up; the snapshot that follows will include it.
                    val remoteTimes = remote.mapTo(HashSet()) { it.time }
                    val localOnly = history.items.value.filter { it.time !in remoteTimes }
                    if (localOnly.isNotEmpty()) {
                        localOnly.chunked(400).forEach { chunk ->
                            val batch = db!!.batch()
                            chunk.forEach { r -> batch.set(results(uid).document(r.time.toString()), toMap(r)) }
                            batch.commit() // resolves on server ack; the local cache applies it immediately
                        }
                        history.replaceAll(remote + localOnly)
                        return@addSnapshotListener
                    }
                }
                history.replaceAll(remote)
                when {
                    snap.metadata.hasPendingWrites() -> setSync(SyncStatus.SYNCING)
                    snap.metadata.isFromCache -> setSync(SyncStatus.OFFLINE)
                    else -> setSync(SyncStatus.SYNCED, synced = true)
                }
            }
    }

    private fun stopSync() {
        listener?.remove()
        listener = null
        syncedUid = null
    }

    suspend fun signIn(activityContext: Context) {
        val auth = auth ?: return
        val clientId = webClientId ?: return
        _error.value = null
        _state.value = AccountState.SigningIn
        try {
            val idToken = googleIdToken(activityContext, clientId)
            auth.signInWithCredential(GoogleAuthProvider.getCredential(idToken, null)).await()
            // The auth state listener takes over from here.
        } catch (e: CancellationException) {
            throw e
        } catch (e: GetCredentialCancellationException) {
            // The user closed the sheet; not an error.
        } catch (e: NoCredentialException) {
            _error.value = AccountError.NO_ACCOUNT
        } catch (e: GetCredentialProviderConfigurationException) {
            _error.value = AccountError.NO_GOOGLE_PLAY
        } catch (e: GetCredentialUnsupportedException) {
            _error.value = AccountError.NO_GOOGLE_PLAY
        } catch (e: GetCredentialException) {
            Log.w(TAG, "credential request failed", e)
            _error.value = AccountError.FAILED
        } catch (e: Exception) {
            Log.w(TAG, "sign-in failed", e)
            _error.value = AccountError.FAILED
        } finally {
            if (_state.value is AccountState.SigningIn) {
                val user = auth.currentUser
                if (user != null) onUser(user) else _state.value = AccountState.SignedOut
            }
        }
    }

    /** Shows Google's account sheet and returns a fresh ID token for Firebase. */
    private suspend fun googleIdToken(activityContext: Context, clientId: String): String {
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(GetSignInWithGoogleOption.Builder(clientId).build())
            .build()
        val credential = CredentialManager.create(activityContext).getCredential(activityContext, request).credential
        if (credential !is CustomCredential || credential.type != GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            throw IllegalStateException("Unexpected credential ${credential.type}")
        }
        return GoogleIdTokenCredential.createFrom(credential.data).idToken
    }

    fun signOut() {
        val auth = auth ?: return
        stopSync()
        auth.signOut()
        scope.launch {
            runCatching { CredentialManager.create(app).clearCredentialState(ClearCredentialStateRequest()) }
        }
    }

    /**
     * Deletes the account: every synced result in Firestore, then the Firebase user itself (Google Play's
     * account-deletion requirement). The history stored on this device stays. If Firebase wants a recent
     * sign-in first, Google's account sheet is shown once to re-confirm, and the deletion is retried.
     */
    suspend fun deleteAccount(activityContext: Context) {
        val auth = auth ?: return
        val user = auth.currentUser ?: return
        val clientId = webClientId ?: return
        stopSync()
        setSync(SyncStatus.SYNCING)
        try {
            results(user.uid).get().await().documents.chunked(400).forEach { chunk ->
                val batch = db!!.batch()
                chunk.forEach { batch.delete(it.reference) }
                batch.commit().await()
            }
            try {
                user.delete().await()
            } catch (e: FirebaseAuthRecentLoginRequiredException) {
                val idToken = googleIdToken(activityContext, clientId)
                user.reauthenticate(GoogleAuthProvider.getCredential(idToken, null)).await()
                user.delete().await()
            }
            runCatching { CredentialManager.create(app).clearCredentialState(ClearCredentialStateRequest()) }
            _state.value = AccountState.SignedOut
        } catch (e: CancellationException) {
            throw e
        } catch (e: GetCredentialCancellationException) {
            startSync(user.uid) // the user backed out of re-confirming; nothing was deleted from the account
        } catch (e: Exception) {
            Log.w(TAG, "delete account failed", e)
            _error.value = AccountError.FAILED
            if (auth.currentUser != null) startSync(user.uid)
        }
    }

    // History changes made on this device. Without an account these are no-ops.

    fun pushAdded(r: TestResult) {
        val uid = syncedUid ?: return
        results(uid).document(r.time.toString()).set(toMap(r))
    }

    fun pushDeleted(time: Long) {
        val uid = syncedUid ?: return
        results(uid).document(time.toString()).delete()
    }

    fun pushCleared(times: List<Long>) {
        val uid = syncedUid ?: return
        times.chunked(400).forEach { chunk ->
            val batch = db!!.batch()
            chunk.forEach { batch.delete(results(uid).document(it.toString())) }
            batch.commit()
        }
    }

    private fun toMap(r: TestResult): Map<String, Any> = buildMap {
        put("t", r.time); put("d", r.downloadMbps); put("u", r.uploadMbps)
        put("p", r.pingMs); put("j", r.jitterMs); put("isp", r.isp); put("srv", r.server)
        put("net", r.network.name); put("src", r.source.name)
        r.downLoadedPingMs?.let { put("dlp", it) }
        r.upLoadedPingMs?.let { put("ulp", it) }
        r.bufferbloatGrade?.let { put("bbg", it) }
    }

    private fun fromDoc(d: DocumentSnapshot): TestResult? = runCatching {
        TestResult(
            time = d.getLong("t") ?: d.id.toLong(),
            downloadMbps = d.getDouble("d") ?: 0.0,
            uploadMbps = d.getDouble("u") ?: 0.0,
            pingMs = d.getDouble("p") ?: 0.0,
            jitterMs = d.getDouble("j") ?: 0.0,
            isp = d.getString("isp").orEmpty(),
            server = d.getString("srv").orEmpty(),
            network = NetworkKind.entries.firstOrNull { it.name == d.getString("net") } ?: NetworkKind.OTHER,
            source = TestSource.entries.firstOrNull { it.name == d.getString("src") } ?: TestSource.CLOUDFLARE,
            downLoadedPingMs = d.getDouble("dlp"),
            upLoadedPingMs = d.getDouble("ulp"),
            bufferbloatGrade = d.getString("bbg"),
        )
    }.getOrNull()

    private companion object {
        const val TAG = "PulseCloud"
        const val MAX_SYNCED = 200
    }
}
